#!/usr/bin/env node
// Convert a LAM export (gaussians.npy) into a standard 3DGS .ply.
//
//   node tools/to-ply.mjs --in me-export --out me.ply
//
// The point is to check the Gaussians *independently of this repo's renderer*:
// any 3DGS viewer should open the result. Conventions match LAM's own
// offset.ply — log scale, logit opacity, SH DC coefficients, wxyz rotation —
// so a viewer that displays LAM's reference correctly will display this too.

import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { loadNpy } from './npy.mjs';

const args = process.argv.slice(2);
const opt = (n, d) => { const i = args.indexOf(`--${n}`); return i >= 0 ? args[i + 1] : d; };

const dir = resolve(opt('in', 'me-export'));
const out = resolve(opt('out', 'me.ply'));

const G = loadNpy(`${dir}/gaussians.npy`);
const n = G.shape[0];
const s = G.shape[1];
if (s < 14) {
  console.error(`gaussians.npy should be (N, 14): xyz scale3 quat4 rgb3 opacity, got ${s} columns`);
  process.exit(1);
}

const C0 = 0.28209479177387814;
const SH_C0 = (rgb) => (rgb - 0.5) / C0;
const logit = (p) => Math.log(Math.min(1 - 1e-6, Math.max(1e-6, p)) / (1 - Math.min(1 - 1e-6, Math.max(1e-6, p))));
const clog = (v) => Math.log(Math.max(1e-12, v));

const props = [
  'x', 'y', 'z', 'nx', 'ny', 'nz',
  'f_dc_0', 'f_dc_1', 'f_dc_2',
  'opacity',
  'scale_0', 'scale_1', 'scale_2',
  'rot_0', 'rot_1', 'rot_2', 'rot_3',
];

const header = [
  'ply',
  'format binary_little_endian 1.0',
  'comment generated by tools/to-ply.mjs',
  `element vertex ${n}`,
  ...props.map((p) => `property float ${p}`),
  'end_header',
  '',
].join('\n');

const body = Buffer.alloc(n * props.length * 4);
let o = 0;
const put = (v) => { body.writeFloatLE(v, o); o += 4; };

for (let i = 0; i < n; i++) {
  const b = i * s;
  const x = G.data[b], y = G.data[b + 1], z = G.data[b + 2];
  const s0 = G.data[b + 3], s1 = G.data[b + 4], s2 = G.data[b + 5];
  const q0 = G.data[b + 6], q1 = G.data[b + 7], q2 = G.data[b + 8], q3 = G.data[b + 9];
  const r = G.data[b + 10], g = G.data[b + 11], bl = G.data[b + 12];
  const op = G.data[b + 13];

  put(x); put(y); put(z);
  put(0); put(0); put(0);
  put(SH_C0(r)); put(SH_C0(g)); put(SH_C0(bl));
  put(logit(op));
  put(clog(s0)); put(clog(s1)); put(clog(s2));
  // LAM stores rot_0..3 as (w, x, y, z)
  put(q0); put(q1); put(q2); put(q3);
}

writeFileSync(out, Buffer.concat([Buffer.from(header, 'ascii'), body]));
console.log(`${n.toLocaleString()} gaussians -> ${out}  (${(body.length / 1e6).toFixed(1)} MB)`);
